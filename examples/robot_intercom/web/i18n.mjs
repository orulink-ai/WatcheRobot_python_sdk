const storageKey = "watcherobot.intercom.language";
export function createI18n({ storage, languages = [] } = {}) {
  let saved;
  try { saved = storage?.getItem(storageKey); } catch { /* Private storage can be unavailable. */ }
  const preferred = languages.find((language) => /^(zh|en)(?:-|$)/i.test(language));
  let locale = ["zh-CN", "en"].includes(saved) ? saved
    : /^zh(?:-|$)/i.test(preferred || "") ? "zh-CN" : "en";
  return {
    get locale() { return locale; },
    setLocale(next) {
      if (!["zh-CN", "en"].includes(next)) throw new RangeError("Unsupported language");
      locale = next;
      try { storage?.setItem(storageKey, next); } catch { /* Switching still works in memory. */ }
    },
    text(source, values = {}) {
      let result = locale === "en" ? english[source] || source : source;
      if (locale === "en" && result === source) {
        for (const prefix of ["请升级机器人固件，缺少：", "通话已关闭，设备释放待重试："]) {
          if (source.startsWith(prefix)) {
            result = english[prefix] + this.text(source.slice(prefix.length));
            break;
          }
        }
      }
      return result.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
    },
  };
}
