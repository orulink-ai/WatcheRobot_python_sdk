const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = require('node:path').resolve(__dirname, '../../examples/joyinside_pi/web') + '/';
const html = fs.readFileSync(root + 'index.html', 'utf8');
const elements = new Map();
class Element {
  constructor() { this.children=[]; this.listeners={}; this.value=''; this.disabled=false; this.textContent=''; this.hidden=false; this.classList={toggle(){},remove(){}}; }
  addEventListener(type, listener) { this.listeners[type]=listener; }
  append(...children) { this.children.push(...children); }
  replaceChildren(...children) { this.children=children; }
  setAttribute(name,value) { this[name]=value; }
  querySelector() { return this.span ||= new Element(); }
}
for (const [,id] of html.matchAll(/\bid="([^"]+)"/g)) elements.set(id,new Element());
let calls=[];
let reply;
const sandbox = vm.createContext({document:{getElementById:id=>elements.get(id),createElement:()=>new Element()}, AbortSignal, setTimeout(){}, fetch(path,options) { calls.push({path,options}); return path === '/api/speech/backend' ? reply() : new Promise(()=>{}); }});
vm.runInContext(fs.readFileSync(root+'app.js','utf8'),sandbox);
const get=id=>elements.get(id);
const base={phase:'paused',enabled:false,connected:true,speech_backend:'joyinside',speech_backends:[{id:'joyinside',label:'JoyInside',configured:true},{id:'doubao',label:'豆包',configured:true}],messages:[]};
const render=state=>vm.runInContext('render('+JSON.stringify(state)+')',sandbox);
(async()=>{
  assert.ok(get('speech-backend'),'speech backend selector is visible');
  render({...base,behavior:{active:false,device_id:null,expression_available:false,motion_available:false}});
  assert.match(get('behavior-capabilities').textContent,/表情待确认.*动作待确认/,'uninitialized capabilities are pending rather than unsupported');
  render(base);
  assert.ok(get('behavior-status'),'automatic behavior status is visible');
  assert.match(get('behavior-status').textContent,/待机/);
  assert.equal(get('emotion-legend').children.length,7,'all supported emotions are explained');
  render({...base,behavior:{active:true,phase:'thinking',emotion:4,expression_available:true,motion_available:true,mouth_sync_available:false,motion_feedback:'commanded',motion_action:'chat_v1_focus',device_id:'robot-test',cleanup_pending:true},timings_ms:{recognition:2847,pi:11186,speech:4944}});
  assert.match(get('behavior-status').textContent,/思考/);
  assert.equal(get('behavior-notice').hidden,true,'active resource ownership is not a cleanup warning');
  assert.equal(get('behavior-emotion').textContent,'专注');
  assert.match(get('behavior-motion').textContent,/已发送/);
  assert.doesNotMatch(get('behavior-motion').textContent,/已到位|已完成|执行成功/);
  assert.match(get('behavior-capabilities').textContent,/表情可用/);
  assert.match(get('behavior-capabilities').textContent,/嘴型.*固件/);
  assert.match(get('behavior-device').textContent,/robot-test/);
  assert.equal(get('timing-recognition').textContent,'2.85 秒');
  assert.equal(get('timing-pi').textContent,'11.19 秒');
  assert.equal(get('timing-speech').textContent,'4.94 秒');
  assert.match(html,/含说话/);
  assert.match(html,/含实际朗读/);
  render({...base,behavior:{active:false,phase:'paused',emotion:5,expression_available:false,motion_available:false,degraded:true,error:'private raw secret token',cleanup_pending:true},timings_ms:{recognition:-1,pi:'99',speech:null}});
  assert.match(get('behavior-status').textContent,/清理|释放|结束/);
  assert.equal(get('behavior-notice').hidden,false);
  assert.match(get('behavior-notice').textContent,/降级/);
  assert.doesNotMatch(get('behavior-notice').textContent,/secret|token/);
  assert.match(get('behavior-capabilities').textContent,/表情不可用/);
  assert.equal(get('timing-recognition').textContent,'—');
  assert.equal(get('timing-pi').textContent,'—');
  assert.equal(get('timing-speech').textContent,'—');
  render({...base,timings_ms:{recognition:0}});
  assert.equal(get('timing-recognition').textContent,'0.00 秒');
  assert.equal(get('behavior-notice').hidden,true,'old degraded warnings clear on confirmed state');
  render({...base,enabled:true,phase:'acknowledging',messages:[{id:88,role:'assistant',kind:'preface',text:'好的，我帮你打开小红书。'}]});
  assert.match(get('phase').textContent,/回应/);
  assert.equal(get('messages').children[0].children[0].textContent,'Pi · 操作前回应');
  render(base);
  assert.equal(get('speech-backend').value,'joyinside');
  const firstOption = get('speech-backend').children[0];
  render(base);
  assert.equal(get('speech-backend').children[0],firstOption,'polling must not rebuild native selection while the user is choosing');
  assert.equal(get('speech-backend').disabled,false);
  assert.match(get('voice-backend-label').textContent,/JoyInside/);
  render({...base,enabled:true,phase:'listening'});
  assert.equal(get('speech-backend').disabled,true);
  render({...base,speech_switch_available:false});
  assert.equal(get('speech-backend').disabled,true,'cleanup also blocks paused switch');
  render({...base,phase:'stopping'});
  assert.equal(get('speech-backend').disabled,true);
  render({...base,speech_backends:[base.speech_backends[0],{id:'doubao',configured:false}]});
  assert.equal(get('speech-backend').children.find(x=>x.value==='doubao').disabled,true);
  assert.match(get('speech-backend-status').textContent,/豆包凭据尚未配置/);
  render(base);
  get('speech-backend').value='doubao';
  let resolve;
  reply=()=>new Promise(r=>resolve=r);
  const pending=get('speech-backend').listeners.change();
  assert.equal(get('speech-backend').disabled,true);
  assert.equal(get('toggle').disabled,true);
  assert.equal(calls.at(-1).path,'/api/speech/backend');
  assert.equal(calls.at(-1).options.body,'{"backend":"doubao"}');
  resolve({ok:true,json:async()=>({...base,speech_backend:'doubao'})});
  await pending;
  assert.equal(get('speech-backend').value,'doubao');
  assert.match(get('voice-backend-label').textContent,/豆包/);
  assert.match(get('voice-backend-detail').textContent,/Application/);
  get('speech-backend').value='joyinside';
  reply=async()=>({ok:false,json:async()=>({error:'private raw secret token'})});
  await get('speech-backend').listeners.change();
  assert.equal(get('speech-backend').value,'doubao','failed switch retains confirmed selection');
  assert.equal(get('speech-backend-error').hidden,false);
  assert.doesNotMatch(get('speech-backend-error').textContent,/secret|token/);
  const before=calls.length;
  render({...base,enabled:true,phase:'listening'});
  await get('speech-backend').listeners.change();
  assert.equal(calls.length,before,'busy switch does not issue a request');
  render({...base,connected:false});
  vm.runInContext('connectionUnavailable = false; renderConnection({state: "idle", online: false})',sandbox);
  get('pairing-code').value='ab1234567';
  get('pairing-code').listeners.input();
  assert.equal(get('pairing-code').value,'123456');
  assert.equal(get('pair').disabled,false,'valid pairing remains enabled when paused and offline');
  render({...base,connected:false,enabled:true,phase:'listening'});
  assert.equal(get('pair').disabled,true,'conversation still prevents pairing');
  console.log('UI behavior assertions passed: automatic behavior, capability degradation, safe commanded motion status, stage durations, backend selection, busy locks, safe errors, pairing preserved.');
})().catch(e=>{console.error(e);process.exitCode=1;});
